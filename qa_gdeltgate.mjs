let pass = 0, fail = 0; const ok = (c, m) => { c ? pass++ : fail++; console.log(`  ${c ? '✓' : '✗'} ${m}`); };
const { gdeltTurn, gdeltTryTurn, GAP_MS, _resetGdeltGateForTests } = await import('./as-diff/gdeltgate.js');
let clock = 100000; const waits = [];
const opts = { now: () => clock, sleep: async (ms) => { waits.push(ms); clock += ms; } };
await gdeltTurn(opts); const t1 = clock;
await gdeltTurn(opts); const t2 = clock;
await gdeltTurn(opts); const t3 = clock;
ok(t2 - t1 === GAP_MS && t3 - t2 === GAP_MS, 'consecutive GDELT requests are spaced at least the gap apart');
clock += 20000; const before = waits.length; await gdeltTurn(opts);
ok(waits.length === before, 'after a long idle the next request goes straight through');
const order = []; clock = 500000;
await Promise.all([1, 2, 3].map(async (i) => { await gdeltTurn(opts); order.push(i); }));
ok(order.join() === '1,2,3', 'concurrent callers pass in arrival order');
_resetGdeltGateForTests(); clock = 900000;
ok(gdeltTryTurn({ now: () => clock }) === true, 'an ambient poll goes when the quota is free');
ok(gdeltTryTurn({ now: () => clock + 1000 }) === false && gdeltTryTurn({ now: () => clock + GAP_MS }) === true, 'an ambient poll inside the gap does not go, and never waits; after the gap it goes');
_resetGdeltGateForTests(); clock = 1000000;
const pending = gdeltTurn({ now: () => clock, sleep: async (ms) => { clock += ms; } });
ok(gdeltTryTurn({ now: () => clock }) === false, 'an ambient poll yields to a waiting media lookup');
await pending;
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
